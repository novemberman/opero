import type {
  ReportAiNarrative,
  ReportFinding,
  ReportMetric,
  ReportModel,
} from "./model.js";

export const DEFAULT_REPORT_TITLE = "Financial X-Ray Report";

export const DISCLOSURES = {
  basis:
    "This report is produced by deterministic calculations on the financial evidence supplied. Its figures depend entirely on the completeness and accuracy of that evidence.",
  notAdvice:
    "This report is not an audit opinion, a credit rating, a forecast, or investment, legal or tax advice.",
  provisionalScore:
    "Scores use provisional heuristic thresholds, not validated industry benchmarks.",
  notScored:
    "No overall score was produced because the evidence did not meet the minimum requirements for scoring.",
  notVerified:
    "This report has not been verified for publication. Treat it as a draft and read the limitations before relying on any figure.",
  simulatedAi:
    "The interpretation section is simulated: it was assembled by fixed rules and was not written by a live AI model.",
  liveAi:
    "The interpretation section was generated by an AI model from the diagnostic results in this report. It may contain errors; the diagnostic tables take precedence.",
} as const;

export type ReportPayloadMetric = {
  code: string;
  label?: string | null;
  dimension?: string | null;
  status: string;
  value?: string | number | null;
  unit?: string | null;
  periodLabel?: string | null;
};

export type ReportPayloadFinding = {
  id?: string | null;
  category: string;
  severity: string;
  title: string;
  explanation?: string | null;
  implication?: string | null;
  suggestedAction?: string | null;
};

/**
 * Snapshot of a diagnostic run. Structurally compatible with
 * `DiagnosticEngineResult` from `@opero/diagnostics` plus the run's
 * organization and period details. Unlisted fields are ignored.
 */
export type ReportSnapshotPayload = {
  organizationName?: string | null;
  periodLabel?: string | null;
  periodStart?: string | null;
  periodEnd?: string | null;
  currency?: string | null;
  metrics: readonly ReportPayloadMetric[];
  findings: readonly ReportPayloadFinding[];
  quality: {
    completeness?: string | number | null;
    consistency?: string | number | null;
    evidenceReliability?: string | number | null;
    diagnosticCoverage?: string | number | null;
  };
  score: {
    status: string;
    overallScore?: number | null;
    limitations?: readonly string[] | null;
  };
  readinessStatus?: string | null;
};

/** Structurally compatible with `AiInterpretationResult` from `@opero/ai`. */
export type ReportAiNarrativeInput = {
  isSimulated: boolean;
  narrative: {
    summary: string;
    keyObservations?: readonly string[] | null;
    risks?: readonly string[] | null;
    limitations?: readonly string[] | null;
  };
  provider?: string | null;
  model?: string | null;
};

export type AssembleReportOptions = {
  title?: string | null;
  aiNarrative?: ReportAiNarrativeInput | null;
  /** Only an explicit `true` on a `SCORED` payload marks the report as verified. */
  verifiedPublication?: boolean;
  /** Appended after the standard disclosures. */
  additionalDisclosures?: readonly string[] | null;
  generatedAt?: Date | string | null;
};

/** Single line of printable text: whitespace collapsed, control characters removed. */
function clean(value: unknown): string | null {
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : null;
  if (typeof value !== "string") return null;
  const cleaned = value
    .replace(/\s+/gu, " ")
    .replace(/[\p{Cc}\p{Cf}]/gu, "")
    .trim();
  return cleaned.length ? cleaned : null;
}

function cleanList(values: readonly unknown[] | null | undefined): string[] {
  const seen = new Set<string>();
  for (const value of values ?? []) {
    const cleaned = clean(value);
    if (cleaned) seen.add(cleaned);
  }
  return [...seen];
}

function describePeriod(payload: ReportSnapshotPayload): string {
  const label = clean(payload.periodLabel);
  if (label) return label;
  const start = clean(payload.periodStart);
  const end = clean(payload.periodEnd);
  if (start && end) return `${start} to ${end}`;
  if (end) return `Period ending ${end}`;
  if (start) return `Period starting ${start}`;
  return "Period not specified";
}

function toIsoTimestamp(value: Date | string | null | undefined): string | null {
  if (value == null) return null;
  const date = value instanceof Date ? value : new Date(value);
  return Number.isNaN(date.getTime()) ? null : date.toISOString();
}

function assembleAiNarrative(input: ReportAiNarrativeInput): ReportAiNarrative | undefined {
  const summary = clean(input.narrative?.summary);
  if (!summary) return undefined;
  return {
    // Anything other than an explicit `false` is treated as simulated, so a
    // narrative of unknown origin is never presented as live AI output.
    isSimulated: input.isSimulated !== false,
    summary,
    keyObservations: cleanList(input.narrative.keyObservations),
    risks: cleanList(input.narrative.risks),
    limitations: cleanList(input.narrative.limitations),
    provider: clean(input.provider),
    model: clean(input.model),
  };
}

/**
 * Builds the report model from a diagnostic snapshot payload and, optionally,
 * an AI narrative. Values are copied as given; nothing is computed or
 * estimated here. The report is non-verified unless `verifiedPublication`
 * is explicitly `true` and the payload carries a produced (`SCORED`) score.
 */
export function assembleReportModel(
  payload: ReportSnapshotPayload,
  options: AssembleReportOptions = {},
): ReportModel {
  const metrics: ReportMetric[] = [];
  for (const metric of payload.metrics) {
    const code = clean(metric.code);
    if (!code) continue;
    metrics.push({
      code,
      label: clean(metric.label) ?? code,
      dimension: clean(metric.dimension),
      status: clean(metric.status) ?? "UNKNOWN",
      value: clean(metric.value),
      unit: clean(metric.unit),
      periodLabel: clean(metric.periodLabel),
    });
  }

  const findings: ReportFinding[] = [];
  for (const finding of payload.findings) {
    const title = clean(finding.title);
    if (!title) continue;
    findings.push({
      id: clean(finding.id),
      category: clean(finding.category) ?? "UNKNOWN",
      severity: clean(finding.severity) ?? "UNKNOWN",
      title,
      explanation: clean(finding.explanation) ?? "",
      implication: clean(finding.implication),
      suggestedAction: clean(finding.suggestedAction),
    });
  }

  const overall =
    typeof payload.score.overallScore === "number" && Number.isFinite(payload.score.overallScore)
      ? payload.score.overallScore
      : null;
  const scoreStatus = clean(payload.score.status) ?? "UNKNOWN";
  const scored = scoreStatus === "SCORED" && overall !== null;

  const aiNarrative = options.aiNarrative ? assembleAiNarrative(options.aiNarrative) : undefined;
  // A report without a produced score is limitations-forward whatever the
  // caller asks for, so it can never be rendered without the banner.
  const verifiedPublication = options.verifiedPublication === true && scored;

  const disclosures = cleanList([
    verifiedPublication ? null : DISCLOSURES.notVerified,
    DISCLOSURES.basis,
    DISCLOSURES.notAdvice,
    scored ? DISCLOSURES.provisionalScore : DISCLOSURES.notScored,
    aiNarrative ? (aiNarrative.isSimulated ? DISCLOSURES.simulatedAi : DISCLOSURES.liveAi) : null,
    ...(options.additionalDisclosures ?? []),
  ]);

  const readinessStatus = clean(payload.readinessStatus);

  return {
    title: clean(options.title) ?? DEFAULT_REPORT_TITLE,
    orgName: clean(payload.organizationName) ?? "Organization not specified",
    period: describePeriod(payload),
    currency: clean(payload.currency),
    generatedAt: toIsoTimestamp(options.generatedAt),
    score: {
      status: scoreStatus,
      overall: scored ? overall : null,
      limitations: cleanList(payload.score.limitations),
    },
    metrics,
    findings,
    quality: {
      completeness: clean(payload.quality.completeness),
      consistency: clean(payload.quality.consistency),
      evidenceReliability: clean(payload.quality.evidenceReliability),
      diagnosticCoverage: clean(payload.quality.diagnosticCoverage),
    },
    ...(readinessStatus ? { readinessStatus } : {}),
    ...(aiNarrative ? { aiNarrative } : {}),
    disclosures,
    verifiedPublication,
  };
}
